"""Headless nameplate generation: parametric OpenSCAD template -> STL -> (optional) slice.

Pipeline
    1. validate + escape the customer text (it ends up inside source code!)
    2. render the .scad source from the template
    3. ``openscad -o plate.stl``                      if OpenSCAD is installed
    4. ``orca-slicer``/``prusa-slicer`` CLI -> G-code  if a slicer is installed
    5. otherwise fall back to geometric estimates so the pipeline keeps flowing in dev

Hebrew (and any RTL script) is supported: the text direction is detected and
passed to OpenSCAD ``text(direction="rtl")``; the font must contain the glyphs.
"""

from __future__ import annotations

import asyncio
import re
import shutil
import unicodedata
from dataclasses import dataclass
from pathlib import Path

PLA_DENSITY_G_CM3 = 1.24
INFILL_FACTOR = 0.55        # shells + 20 % infill, relative to a solid body
GRAMS_PER_MINUTE = 0.9      # rough throughput of a 0.4 mm nozzle at standard quality

ALLOWED_PUNCT = set(" -'.&!,״׳\"")
MAX_LEN = 40


class InvalidText(ValueError):
    pass


@dataclass(frozen=True)
class NameplateSpec:
    text: str
    width_mm: float = 120.0
    height_mm: float = 35.0
    thickness_mm: float = 3.0
    text_height_mm: float = 1.6
    corner_radius_mm: float = 4.0
    font: str = "Noto Sans Hebrew:style=Bold"


@dataclass(frozen=True)
class NameplateResult:
    source_path: Path
    artifact_path: Path
    footprint_mm: tuple[float, float]
    est_grams: float
    est_minutes: float
    sliced: bool


def validate_text(text: str) -> str:
    text = unicodedata.normalize("NFC", text).strip()
    if not text:
        raise InvalidText("empty text")
    if len(text) > MAX_LEN:
        raise InvalidText(f"text longer than {MAX_LEN} characters")
    for ch in text:
        if not (ch.isalnum() or ch in ALLOWED_PUNCT):
            raise InvalidText(f"character {ch!r} not allowed")
    return text


def scad_string(text: str) -> str:
    """Escape for an OpenSCAD string literal (prevents code injection)."""
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def is_rtl(text: str) -> bool:
    return any(unicodedata.bidirectional(ch) in ("R", "AL") for ch in text)


def render_scad(spec: NameplateSpec) -> str:
    text = validate_text(spec.text)
    # Shrink the font for long texts so it stays within 85 % of the plate width.
    font_size = min(spec.height_mm * 0.5, spec.width_mm * 0.85 / max(len(text) * 0.62, 1))
    direction = "rtl" if is_rtl(text) else "ltr"
    r = spec.corner_radius_mm
    return f"""// generated by printfarm personalization agent - do not edit
$fn = 48;
w = {spec.width_mm}; h = {spec.height_mm}; t = {spec.thickness_mm}; r = {r};
module plate() {{
  hull() for (x = [r, w - r], y = [r, h - r]) translate([x, y, 0]) cylinder(r = r, h = t);
}}
union() {{
  plate();
  translate([w / 2, h / 2, t])
    linear_extrude(height = {spec.text_height_mm})
      text({scad_string(text)}, size = {font_size:.2f}, font = {scad_string(spec.font)},
           halign = "center", valign = "center", direction = "{direction}");
}}
"""


def estimate(spec: NameplateSpec) -> tuple[float, float]:
    """(grams, minutes) from geometry when no slicer is available."""
    base_cm3 = spec.width_mm * spec.height_mm * spec.thickness_mm / 1000
    text_cm3 = spec.width_mm * 0.85 * spec.height_mm * 0.5 * 0.35 * spec.text_height_mm / 1000
    grams = (base_cm3 + text_cm3) * PLA_DENSITY_G_CM3 * INFILL_FACTOR
    return round(grams, 1), round(grams / GRAMS_PER_MINUTE + 5, 1)


async def _run(*cmd: str, timeout: float = 300) -> None:
    proc = await asyncio.create_subprocess_exec(*cmd, stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE)
    try:
        _, err = await asyncio.wait_for(proc.communicate(), timeout)
    except TimeoutError:
        proc.kill()
        raise RuntimeError(f"{cmd[0]} timed out") from None
    if proc.returncode != 0:
        raise RuntimeError(f"{cmd[0]} failed: {err.decode(errors='replace')[-500:]}")


async def generate(spec: NameplateSpec, out_dir: Path, name: str) -> NameplateResult:
    out_dir.mkdir(parents=True, exist_ok=True)
    scad = out_dir / f"{name}.scad"
    scad.write_text(render_scad(spec), encoding="utf-8")
    grams, minutes = estimate(spec)
    artifact, sliced = scad, False

    if shutil.which("openscad"):
        stl = out_dir / f"{name}.stl"
        await _run("openscad", "-o", str(stl), str(scad))
        artifact = stl
        slicer = shutil.which("orca-slicer") or shutil.which("prusa-slicer")
        if slicer:
            # Slicer profiles are site-specific; see docs/architecture/02-agent-catalog.md.
            gcode = out_dir / f"{name}.gcode"
            await _run(slicer, "--export-gcode", "--output", str(gcode), str(stl))
            artifact, sliced = gcode, True
            # TODO: parse "; filament used [g]" / "; estimated printing time" from the G-code footer.

    return NameplateResult(scad, artifact, (spec.width_mm, spec.height_mm), grams, minutes, sliced)


_SAFE_NAME = re.compile(r"[^A-Za-z0-9_.-]")


def safe_name(order_id: str) -> str:
    return _SAFE_NAME.sub("_", order_id)[:80]
